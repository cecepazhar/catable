#!/usr/bin/env bash
# Generates throwaway credentials and an SSH key for dev/compose.test.yml.
# Output (gitignored): dev/.env, dev/.secrets/id_ed25519{,.pub}
# Pass --force to regenerate dev/.env (then recreate the stack with `down -v`).
set -euo pipefail

cd "$(dirname "$0")"
dev_dir="$(pwd)"

mkdir -p .secrets
chmod 700 .secrets
if [[ ! -f .secrets/id_ed25519 ]]; then
    ssh-keygen -q -t ed25519 -N "" -C catable-it -f .secrets/id_ed25519
fi

if [[ -f .env && "${1:-}" != "--force" ]]; then
    echo "dev/.env already exists (use --force to regenerate)"
    exit 0
fi

# Reads a bounded amount of entropy so no stage dies of SIGPIPE under pipefail.
rand() { head -c 48 /dev/urandom | base64 | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-24; }

db_user=catable
db_pass="$(rand)"
root_pass="$(rand)"
ssh_user=catable
ssh_pass="$(rand)"
pg_port=55432
mysql_port=53306
mariadb_port=53307
ssh_port=52222

umask 077
cat >.env <<EOF
# Generated by dev/it-setup.sh — throwaway credentials for the local test stack.
CATABLE_IT_DB_USER=${db_user}
CATABLE_IT_DB_PASSWORD=${db_pass}
CATABLE_IT_DB_ROOT_PASSWORD=${root_pass}
CATABLE_IT_PG_PORT=${pg_port}
CATABLE_IT_MYSQL_PORT=${mysql_port}
CATABLE_IT_MARIADB_PORT=${mariadb_port}

CATABLE_IT_PG_URL=postgres://${db_user}:${db_pass}@127.0.0.1:${pg_port}/catable_it
CATABLE_IT_MYSQL_URL=mysql://${db_user}:${db_pass}@127.0.0.1:${mysql_port}/catable_it
CATABLE_IT_MARIADB_URL=mysql://${db_user}:${db_pass}@127.0.0.1:${mariadb_port}/catable_it

CATABLE_IT_SSH_HOST=127.0.0.1
CATABLE_IT_SSH_PORT=${ssh_port}
CATABLE_IT_SSH_USER=${ssh_user}
CATABLE_IT_SSH_PASSWORD=${ssh_pass}
CATABLE_IT_SSH_KEY_PATH=${dev_dir}/.secrets/id_ed25519
EOF

echo "wrote dev/.env and dev/.secrets/id_ed25519"
